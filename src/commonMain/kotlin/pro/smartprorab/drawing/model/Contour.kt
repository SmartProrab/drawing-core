package pro.smartprorab.drawing.model

/**
 * Контур потолка. Замыкание неявное: последняя вершина соединяется с первой, первая точка не повторяется.
 * Обход после нормализации — по часовой стрелке (удвоенная знаковая площадь < 0).
 * Диагонали не хранятся: длину между любыми вершинами считает библиотека по точкам.
 */
data class Contour(
    val points: List<Point>,
    val type: ContourType = ContourType.MAIN,
)
